KEY = os.environ.get("YANDEX_API_KEY", "")
FOLDER = os.environ.get("YANDEX_FOLDER_ID", "b1g1jn7q5cb0cqhmg1hm")
MODEL = f"gpt://{FOLDER}/yandexgpt-5-pro"
if "--model" in sys.argv:
    MODEL = sys.argv[sys.argv.index("--model") + 1]
URL = "https://llm.api.cloud.yandex.net/v1/chat/completions"

FACTS = """
- 14 лет в HR IT и цифровой трансформации; начал с SAP HCM-консалтинга, далее — управление HR IT и крупными проектами.
- РусГидро: переход с SAP HCM на 1С ЗУП (бюджет >110 млн руб., 2 подрядчика, проект признан «проектом года»), внедрение КЭДО на базе HRLink (60% кадровых документов в ЭДО, цифровой доступ к HR-сервисам у 80% персонала), LMS Knomary (70 000+ сотрудников), HR-портал (ESS/MSS), ATS Skillaz (проверка кандидатов и приём ×2 быстрее, ошибок −14%), система организационной структуры.
- Управлял командами 40+ человек, несколькими подрядчиками, бюджетами до 110 млн руб.
- Полный цикл: сбор и формализация требований, подготовка ТЗ, выбор решений, внедрение, тестирование, запуск в промышленную эксплуатацию.
- ИИ: GenAI/LLM, RAG, function calling, AI-агенты, контекстный инжиниринг; реализовал ИИ-ассистента, финансового ассистента, автоматизацию процессов.
"""

SYSTEM = """Ты — Хайрбек Ажимов, эксперт HR-Tech (14 лет) и специалист по внедрению ИИ.
Ты пишешь сопроводительные письма работодателям на русском языке.

СТИЛЬ (строго):
— Начало: «Добрый день!» и отдельной строкой «Меня зовут Хайрбек Ажимов.»
— Плавное, уверенное повествование: связные абзацы, БЕЗ списков, БЕЗ тире-перечислений, БЕЗ формата отчёта.
— НЕ перегружай цифрами: 1–2 самых сильных факта/метрики, остальное — по смыслу.
— Тон: спокойная уверенность, без пафоса, без панибратства, без канцелярита.
— Свяжи свой опыт с конкретной потребностью из вакансии (покажи понимание задачи).
— Объём: 4–5 абзацев, 800–1150 знаков.

ПЕРСОНАЛИЗАЦИЯ (главное, ради чего письмо):
1. Выдели 2–3 ключевых требования вакансии и ответь на КАЖДОЕ своим опытом
   по схеме «у вас нужно X → у меня это было так: <факт с результатом>».
2. ЗЕРКАЛЬ 2–3 формулировки работодателя его же словами (важно и для рекрутёра,
   и для автоматического скоринга hh).
3. Приведи 1–2 конкретных кейса, прямо отвечающих на боль вакансии, с метрикой.
4. Покажи понимание продукта/задачи компании — почему именно к ним.
5. Убери обобщения («накопил значительный опыт», «широкий спектр») — только конкретика.

ЗАПРЕЩЕНО: выдумывать факты, цифры, компании, которых нет в списке фактов.
Не используй markdown (звёздочки, решётки).

Финал письма строго такой:
«Буду рад обсудить, как мой опыт может быть применён в {company}.»

Подпись строго такая:
С уважением,
Хайрбек Ажимов
тел. 89253560809
тг. @khayrbek"""

def main():
    a = sys.argv[1:]
    if "--model" in a:
        i = a.index("--model")
        a = a[:i] + a[i + 2:]
    data = json.load(open(a[0]))
    out = a[1]
    user = f"""Напиши сопроводительное письмо на вакансию.

Вакансия: {data.get('title','')}
Компания: {data.get('company','')}

Требования вакансии (текст объявления):
{data.get('description','')[:3500]}

Сначала выдели 3 ключевых требования этой вакансии и подбери к каждому свой
подтверждающий факт из списка выше, затем напиши письмо, отвечая на них.

ФАКТЫ обо мне (использовать только их):
{FACTS}"""

    payload = {
        "model": MODEL,
        "messages": [
            {"role": "system", "content": SYSTEM.replace("{company}", data.get('company',''))},
            {"role": "user", "content": user},
        ],
        "max_tokens": 1500,
        "temperature": 0.5,
    }
    r = subprocess.run(["curl","-s","--max-time","90","-X","POST",URL,
        "-H", f"Authorization: Api-Key {KEY}",
        "-H","Content-Type: application/json",
        "-d", json.dumps(payload, ensure_ascii=False)],
        capture_output=True, text=True, timeout=100)
    try:
        res = json.loads(r.stdout)
        text = res["choices"][0]["message"]["content"].strip()
    except Exception as e:
        print("ОШИБКА:", str(e)[:200]); print(r.stdout[:500]); sys.exit(1)
    open(out, "w").write(text)
    print(text)
    print(f"\n[сохранено: {out}, {len(text)} знаков]")

main()
